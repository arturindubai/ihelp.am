export const DEFAULT_COUNTRY = "AM";

/**
 * Армения первой, остальные по алфавиту. Сравнение по кодам символов, а не localeCompare:
 * порядок в выпадающем списке обязан совпасть на сервере и в браузере, иначе гидратация ругается.
 */
export const COUNTRIES: Country[] = RAW.split("\n")
  .map((line) => {
    const [iso, dial, name] = line.split("|");
    return { iso, dial, name };
  })
  .sort((a, b) => (a.iso === DEFAULT_COUNTRY ? -1 : b.iso === DEFAULT_COUNTRY ? 1 : a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

/** Эмодзи-флаг из ISO-кода: две региональные буквы Unicode (на Windows-десктопе браузеры рисуют буквы вместо флага) */
export const flagEmoji = (iso: string) => String.fromCodePoint(...[...iso.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));

export const countryByIso = (iso?: string | null) => (iso ? COUNTRIES.find((c) => c.iso === iso.toUpperCase()) : undefined);

/** Общий код у нескольких стран (+1 — США/Канада, +7 — Россия/Казахстан): предпочитаем эти */
const PREFER = ["US", "RU"];

/** Страна по началу международного номера: самый длинный совпавший код, при равенстве — из PREFER */
export function countryByPhone(e164: string): Country | undefined {
  const digits = e164.replace(/\D/g, "");
  let best: Country | undefined;
  for (const c of COUNTRIES) {
    if (!digits.startsWith(c.dial)) continue;
    if (!best || c.dial.length > best.dial.length || (c.dial.length === best.dial.length && PREFER.includes(c.iso) && !PREFER.includes(best.iso))) best = c;
  }
  return best;
}
